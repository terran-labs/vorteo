// Extracts the approved master's loop shading as a small black overlay.
// Drawing it over the vector silhouette equals multiplying the tint by the
// master's luminance, without loading the master or compositing image masks.

const PADDING = 4;
// The master's outer two pixels carry an antialiasing matte against black.
const EDGE = 2;
// Darkness above this marks the shaded turn; fainter tails inside its box are kept.
const THRESHOLD = 20 / 255;

/**
 * @param {Buffer} rgba 8-bit RGBA pixels of the square master.
 * @param {number} size Width and height of the master in pixels.
 * @returns {{ x: number, y: number, width: number, height: number, pixels: Buffer }}
 *   The overlay box in master pixels and its RGBA pixels.
 */
export function shadingOverlay(rgba, size) {
  const alpha = (x, y) => rgba[(y * size + x) * 4 + 3];
  // The edge matte is not shading; the vector silhouette antialiases its own edge.
  const interior = (x, y) => {
    for (let dy = -EDGE; dy <= EDGE; dy++)
      for (let dx = -EDGE; dx <= EDGE; dx++) {
        const nx = x + dx;
        const ny = y + dy;
        if (nx < 0 || ny < 0 || nx >= size || ny >= size || alpha(nx, ny) < 128) return false;
      }
    return true;
  };
  const darkness = new Float64Array(size * size).fill(-1);
  let minX = size;
  let minY = size;
  let maxX = -1;
  let maxY = -1;
  for (let y = 0; y < size; y++)
    for (let x = 0; x < size; x++) {
      if (!interior(x, y)) continue;
      const i = (y * size + x) * 4;
      const d = 1 - (0.2126 * rgba[i] + 0.7152 * rgba[i + 1] + 0.0722 * rgba[i + 2]) / 255;
      darkness[y * size + x] = d;
      if (d <= THRESHOLD) continue;
      minX = Math.min(minX, x);
      minY = Math.min(minY, y);
      maxX = Math.max(maxX, x);
      maxY = Math.max(maxY, y);
    }
  if (maxX < 0) throw new Error("The master has no loop shading to extract");
  const x0 = Math.max(0, minX - PADDING);
  const y0 = Math.max(0, minY - PADDING);
  const x1 = Math.min(size, maxX + PADDING + 1);
  const y1 = Math.min(size, maxY + PADDING + 1);
  // Carry shading across the edge pixels so the silhouette's clip, not a
  // missing overlay pixel, decides where the shadow ends.
  const known = (x, y) => (x >= 0 && y >= 0 && x < size && y < size ? darkness[y * size + x] : -1);
  const neighborMean = (x, y) => {
    const values = [-1, 0, 1]
      .flatMap((dy) => [-1, 0, 1].map((dx) => known(x + dx, y + dy)))
      .filter((d) => d >= 0);
    return values.length ? values.reduce((sum, d) => sum + d, 0) / values.length : -1;
  };
  for (let pass = 0; pass <= EDGE; pass++) {
    const next = darkness.slice();
    for (let y = y0; y < y1; y++)
      for (let x = x0; x < x1; x++)
        if (darkness[y * size + x] < 0) next[y * size + x] = neighborMean(x, y);
    darkness.set(next);
  }
  const width = x1 - x0;
  const height = y1 - y0;
  const pixels = Buffer.alloc(width * height * 4);
  for (let y = 0; y < height; y++)
    for (let x = 0; x < width; x++)
      pixels[(y * width + x) * 4 + 3] = Math.round(
        255 * Math.max(0, darkness[(y0 + y) * size + x0 + x]),
      );
  return { x: x0, y: y0, width, height, pixels };
}

const BOOT_START = "/* Generated from the master by generate-vorteo-icons.mjs: start */";
const BOOT_END = "/* Generated from the master by generate-vorteo-icons.mjs: end */";

/**
 * Writes the app's mark module and the startup loader's inline mark from the
 * traced silhouette and the encoded shading overlay.
 * @param {{ path: string, shading: { x: number, y: number, width: number, height: number }, shadingUri: string, size: number }} mark
 * @returns {{ module: string, replaceBootMark: (html: string) => string }}
 */
export function renderMarkSources({ path, shading, shadingUri, size }) {
  const { x, y, width, height } = shading;
  const module = `// Generated by scripts/generate-vorteo-icons.mjs from the approved master.
// Inline vectors and a small overlay draw the mark without fetching the master.

/** The master's traced silhouette, in potrace's tenfold, vertically flipped units. */
export const VORTEO_MARK_PATH = ${JSON.stringify(path)};

/** The master's loop shading as black alpha, placed in the ${size}-unit view box. */
export const VORTEO_MARK_SHADING = ${JSON.stringify({ x, y, width, height, uri: shadingUri })} as const;
`;
  const silhouette = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><path transform="translate(0 ${size}) scale(0.1 -0.1)" d="${path}"/></svg>`;
  const mask = `url("data:image/svg+xml,${encodeURIComponent(silhouette)}") center / contain no-repeat`;
  const percent = (value) => `${+(value * 100).toFixed(4)}%`;
  // Background position percentages align the overlay's own point with the box's.
  const css = `${BOOT_START}
        background-image:
          url("${shadingUri}"),
          linear-gradient(135deg, var(--boot-mark-start, #ffffff), var(--boot-mark-end, #c7c7cc));
        background-size:
          ${percent(width / size)} ${percent(height / size)},
          100% 100%;
        background-position:
          ${percent(x / (size - width))} ${percent(y / (size - height))},
          0 0;
        background-repeat: no-repeat;
        -webkit-mask: ${mask};
        mask: ${mask};
        ${BOOT_END}`;
  return {
    module,
    replaceBootMark(html) {
      const start = html.indexOf(BOOT_START);
      const end = html.indexOf(BOOT_END);
      if (start < 0 || end < start) throw new Error("index.html lacks the generated mark markers");
      return html.slice(0, start) + css + html.slice(end + BOOT_END.length);
    },
  };
}
